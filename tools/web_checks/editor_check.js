const path = require('path');
const { ROOT, chromium, check, done, serve } = require('./common');
(async () => {
  const srv = await serve(path.join(ROOT, 'assets/xcoder'), 8791);
  const b = await chromium.launch(); const p = await b.newPage(); const errs = [];
  await p.exposeFunction('__ev', () => {}); await p.addInitScript(() => { window.flutter_inappwebview = { callHandler: (n, o) => window.__ev(o) }; });
  p.on('pageerror', e => errs.push(String(e))); p.on('response', r => { if (r.status() >= 400) errs.push(r.status() + ' ' + r.url()); });
  await p.goto('http://localhost:8791/editor.html'); await p.waitForTimeout(400);
  const c = (n, a) => p.evaluate(([n, a]) => nx.cmd(n, a), [n, a]);
  await c('open', { id: 'a', content: 'function foo(){\n  var x = ;\n}\nclass Foo {}\n', mode: 'javascript' });
  await p.waitForTimeout(2500);
  const ann = await c('annotations');
  check('JavaScript linting (worker) reports the syntax error', ann.some(a => a.type === 'error' && a.row === 1), ann);
  check('outline finds function and class', JSON.stringify((await c('outline')).map(o => o.name)) === '["foo","Foo"]');
  for (const t of ['one_dark', 'dracula', 'monokai', 'github_dark', 'tomorrow_night', 'nord_dark', 'github', 'chrome']) await c('settings', { theme: t });
  await c('gotoLine', { row: 3 }); await c('toggleComment');
  check('toggle comment', (await c('getValue')).split('\n')[3].startsWith('// class'));
  await c('undo'); check('undo', (await c('getValue')).split('\n')[3] === 'class Foo {}');
  check('regex replace all (case-sensitive)', await c('replaceAll', { query: 'fo+\\b', replacement: 'bar', regex: true, caseSensitive: true }) === 1);
  await p.click('#ed'); await p.keyboard.press('End'); await p.keyboard.press('Enter'); await p.keyboard.type('ba', { delay: 80 }); await p.waitForTimeout(800);
  check('autocomplete popup while typing', await p.evaluate(() => { const e = document.querySelector('.ace_autocomplete'); return !!e && e.style.display !== 'none'; }));
  await p.keyboard.press('Escape');
  await c('open', { id: 'j', content: '{"a":1,"b":[1,2]}', mode: 'json' });
  check('format JSON', (await c('format')).ok && (await c('getValue', { id: 'j' })).includes('\n  "a": 1'));
  await c('open', { id: 'h', content: '<html><body><div><p>hi</p></div></body></html>', mode: 'html' }); await p.waitForTimeout(700);
  check('format HTML', (await c('format')).ok && (await c('getValue', { id: 'h' })).split('\n').length > 4);
  await c('setMode', { id: 'h', mode: 'python' });
  check('format refuses unsupported languages', (await c('format')).ok === false);
  check('switch / close sessions', await c('switchTo', { id: 'a' }) === true && await c('close', { id: 'j' }) === true);
  check('unknown commands are rejected', !!(await c('nope')).error);
  check('no page errors or missing files', errs.length === 0, errs);
  await b.close(); srv.close(); done();
})();
